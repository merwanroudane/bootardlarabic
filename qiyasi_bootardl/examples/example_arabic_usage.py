# -*- coding: utf-8 -*-
"""مثال استخدام عربي لمكتبة قياسي BootARDL."""
from qiyasi_bootardl import اختبار_ARDL_بالبوتستراب
from qiyasi_bootardl.datasets import تحميل_بيانات_كلية


def main():
    البيانات = تحميل_بيانات_كلية()

    النتيجة = اختبار_ARDL_بالبوتستراب(
        البيانات,
        المتغير_التابع="الناتج",
        المتغيرات_المستقلة=["الاستثمار", "الانفتاح"],
        الحالة=3,
        أقصى_إبطاء=4,
        معيار_اختيار_ARDL="AIC",
        عدد_تكرارات_البوتستراب=500,
        عشوائية=2024,
        طباعة_التقدم=True,
    )

    print(النتيجة.ملخص())
    print("\n=== التفسير ===")
    print(النتيجة.تفسير())

    print("\n=== جدول الإحصائيات ===")
    print(النتيجة.جدول_الإحصائيات())

    print("\n=== القيم الحرجة بالبوتستراب ===")
    print(النتيجة.جدول_البوتستراب())

    # تقرير HTML
    النتيجة.تقرير_HTML("تقرير_عربي.html")
    print("\nتم حفظ التقرير في: تقرير_عربي.html")

    # الرسوم البيانية العربية
    الملفات = النتيجة.حفظ_كل_الرسوم("الرسوم", "تحليل")
    print("تم حفظ الرسوم:")
    for ملف in الملفات:
        print("  ", ملف)


if __name__ == "__main__":
    main()
